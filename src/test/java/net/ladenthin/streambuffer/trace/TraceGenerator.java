package net.ladenthin.streambuffer.trace;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;
import java.util.Arrays;
import java.util.HashMap;
import java.util.List;
import java.util.Map;

/**
 * Records traces of the scenarios of roadmap A6 and writes each as a TLA+ module with its TLC
 * configuration, for {@code src/test/tla/trace.sh}: {@code Trace_<scenario>_<seed>.tla} extends
 * {@code TraceStreamBuffer.tla} and defines the constants and the trace.
 */
public final class TraceGenerator {

    /** The scenarios: the model's configurations of the current code, see {@code check.sh}. */
    static final List<TraceScenario> SCENARIOS = Arrays.asList(
            // read() readers (Condition2, Condition3)
            new TraceScenario("Bytes2", 4, 1, 1, 2, 0, 0),
            new TraceScenario("Bytes3", 4, 1, 1, 3, 0, 0),
            // records of 2 bytes, writes of 1 and of 3 bytes (Records2, Chunks2)
            new TraceScenario("Records2", 4, 1, 2, 0, 2, 0),
            new TraceScenario("Chunks2", 6, 3, 2, 0, 2, 0),
            // read() next to a record reader (Mixed2)
            new TraceScenario("Mixed2", 4, 1, 2, 1, 1, 0),
            // waitForAtLeast(2) next to a reader (WaitAndRead2, WaitChecked2)
            new TraceScenario("WaitAndRead2", 4, 1, 2, 1, 0, 1),
            new TraceScenario("WaitChecked2", 4, 2, 2, 0, 1, 1),
            // larger: three read() readers of 8 bytes, three record readers of writes of 3
            // bytes, two waiters next to a reader, a waiter next to a reader of 3-byte records
            new TraceScenario("Bytes3x8", 8, 1, 1, 3, 0, 0),
            new TraceScenario("Records3", 8, 3, 2, 0, 3, 0),
            new TraceScenario("Wait2", 6, 1, 2, 1, 0, 2),
            new TraceScenario("WaitRecords", 6, 2, 3, 0, 1, 1));

    private TraceGenerator() {}

    /**
     * Records and writes the traces.
     *
     * @param args the output directory, the number of seeds per scenario, the yield probability
     *     in 1/256
     * @throws Exception if a run fails or a file cannot be written
     */
    public static void main(String[] args) throws Exception {
        final Path dir = Paths.get(args[0]);
        final int seeds = Integer.parseInt(args[1]);
        final int yieldPer256 = Integer.parseInt(args[2]);
        Files.createDirectories(dir);
        for (TraceScenario s : SCENARIOS) {
            for (int seed = 1; seed <= seeds; seed++) {
                final List<TraceRecorder.Event> events = s.run(seed, yieldPer256);
                write(dir, s, seed, events);
            }
        }
    }

    /**
     * Writes one trace.
     *
     * @param dir the directory
     * @param s the scenario
     * @param seed the seed
     * @param events the recorded events
     * @return the module's name
     * @throws IOException if a file cannot be written
     */
    static String write(Path dir, TraceScenario s, long seed, List<TraceRecorder.Event> events) throws IOException {
        final String module = "Trace_" + s.name + "_" + seed;
        final StringBuilder b = new StringBuilder();
        b.append("---- MODULE ").append(module).append(" ----\n");
        b.append("\\* Generated by net.ladenthin.streambuffer.trace.TraceGenerator: ")
                .append(s)
                .append('\n');
        b.append("EXTENDS TraceStreamBuffer\n");
        b.append("TReaders == ").append(set(s.readers())).append('\n');
        b.append("TByteReaders == ").append(set(s.byteReaderNames())).append('\n');
        b.append("TWaitCallers == ").append(set(s.waitCallerNames())).append('\n');
        b.append("TBytes == ").append(s.bytes).append('\n');
        b.append("TChunkLen == ").append(s.chunkLen).append('\n');
        b.append("TReadLen == ").append(s.readLen).append('\n');
        b.append("TTrace == <<\n");
        final Map<String, Integer> calls = new HashMap<>();
        for (int i = 0; i < events.size(); i++) {
            b.append(i == 0 ? "  " : ", ").append(line(events.get(i), calls)).append('\n');
        }
        b.append(">>\n====\n");
        Files.write(dir.resolve(module + ".tla"), b.toString().getBytes(StandardCharsets.UTF_8));
        final String cfg = "CONSTANTS\n"
                + "    Readers <- TReaders\n"
                + "    ByteReaders <- TByteReaders\n"
                + "    WaitCallers <- TWaitCallers\n"
                + "    Bytes <- TBytes\n"
                + "    ChunkLen <- TChunkLen\n"
                + "    ReadLen <- TReadLen\n"
                + "    TraceLog <- TTrace\n"
                + "    K = 6\n"
                // spurious wake-ups of Condition.await() a trace may have (the JDK allows them)
                + "    Spurious = 3\n"
                + "    Protocol = \"condition\"\n"
                + "    ReCheck = TRUE\n"
                + "    AtomicRead = TRUE\n"
                + "    CountOnce = TRUE\n"
                + "    CheckedReturn = TRUE\n"
                + "INIT TraceInit\n"
                + "NEXT TraceNext\n"
                + "INVARIANT TraceNotDone\n"
                + "CHECK_DEADLOCK FALSE\n";
        Files.write(dir.resolve(module + ".cfg"), cfg.getBytes(StandardCharsets.UTF_8));
        return module;
    }

    private static String line(TraceRecorder.Event e, Map<String, Integer> calls) {
        final String m;
        final String a;
        final int n;
        final int hash = e.site.indexOf('#');
        if (hash >= 0) {
            final int dot = e.site.lastIndexOf('.', hash);
            m = e.site.substring(0, dot);
            a = e.site.substring(dot + 1, hash);
            n = Integer.parseInt(e.site.substring(hash + 1));
        } else {
            m = "";
            a = e.site;
            // the calls of the thread that returned data so far
            n = a.equals("ret") ? calls.merge(e.thread, 1, Integer::sum) : calls.getOrDefault(e.thread, 0);
        }
        final StringBuilder bytes = new StringBuilder("<<");
        for (int i = 0; i < e.bytes.size(); i++) {
            bytes.append(i == 0 ? "" : ", ").append(e.bytes.get(i));
        }
        bytes.append(">>");
        return "[t |-> \"" + e.thread + "\", m |-> \"" + m + "\", a |-> \"" + a + "\", n |-> " + n + ", v |-> "
                + e.value + ", b |-> " + bytes + "]";
    }

    private static String set(List<String> names) {
        final StringBuilder b = new StringBuilder("{");
        for (int i = 0; i < names.size(); i++) {
            b.append(i == 0 ? "" : ", ").append('"').append(names.get(i)).append('"');
        }
        return b.append('}').toString();
    }
}
